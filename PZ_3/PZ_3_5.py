# Ввести двузначное число. Если сумма цифр числа четна, то увеличить
# число на 2, в противном случае уменьшить на 2

n = input('Введите двузначное число: ')

while True:
    try:
        n = int(n)
        if 10 <= n <= 99:
            break
        else:
            print('Число должно быть двузначным!')
            n = input("Введите двузначное число: ")
    except ValueError:
        print('Неправильно ввели!')
        n = input('Введите двузначное число: ')

# Разбиваем число
a = abs(n) // 10
b = abs(n) % 10
c = a + b

# Проверяем суммму на четность
if c % 2 == 0:
    n = n + 2
else:
    n = n - 2

print("Результат:", n)