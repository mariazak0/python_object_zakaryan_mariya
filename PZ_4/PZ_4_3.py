# Ввести 4 числа. Найти и вывести на экран сумму и количество отрицательных чисел

a = 0 #Сумма отрицательных чисел
b = 0 #количество отрицательных чисел
i = 1 #счетчик цикла

while i <= 4:
    n = input(f'Введите число {i}:')

    while type(n) != int:
        try:
            n = int(n)
        except ValueError:
            print('Неправильно ввели!')
            n = input(f'Введите число {i}:')

    # Проверка на знак
    if n < 0:
        a += n
        b += 1
    i += 1
print('Сумма отрицательных чисел:', a)
print("Количество отрицательных чисел:", b)
