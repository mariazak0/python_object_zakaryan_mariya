# Дано целое число N (>1). Найти наименьшее целое число K, при котором
# выполняется неравенство 3**k>N
n = input('Введите целое число N (>1):')

while type(n) != int:
    try:
        n = int(n)
    except ValueError:
        print('Неправильно ввели!')
        n = input('Введите целое число N (>1):')
K = 0  # Начальное значение степени
A = 1  # Текущее значение 3**K

# Цикл выполняется, пока 3**K меньше или равно N
while A <= n:
    K += 1
    A *= 3

print('Наименьшее число K:',K)