# Ввести 4 числа. Найти и вывести количество четных чисел
a = 0
i = 1
while i <= 4:
    n = input(f'Введите число {i}:')

    while type(n) != int:
        try:
            n = int(n)
        except ValueError:
            print('Неправильно ввели!')
            n = input(f'Введите число {i}:')

    # Проверка на четность
    if n % 2 == 0:
        a += 1
    i += 1
print('Количество четных чисел:',a)