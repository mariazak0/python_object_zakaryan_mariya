# Дано целое число N(>0). Найти произведение 1.1 * 1.2 * 1.3 ...(N сомножителей)

n = input('Введите количество сомножителей N (>0):')

while type(n) != int:
    try:
        n = int(n)
    except ValueError:
        print('Непрвильно ввели!')
        n = input('Введите количество сомножителей N (>0):')

a = 1.0 # Начальное значение
i = 1 # Счетчик сомножителей

# Цикл для вычисления произведения N множителей
while i <= n:
    a *= (1.0 + 0.1 * i)
    i += 1
print('Произведение сомножителей:',a)