# Дано целое число. Если оно является положительным, то прибавь к нему 20,
# в противном случае вычесть из него 5

n = input('Введите целое число:')

while type(n) != int:
    try:
        n = int(n)
    except ValueError:
        print('Неправильно ввели!')
        n = input('Введите целое число:')

# Проверка знака
if n > 0:
    n = n + 20
else:
    n = n - 5
print("Результат:",n)