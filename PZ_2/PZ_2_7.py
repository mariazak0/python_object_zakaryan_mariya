# Даны два числа. Если их сумма кратна 5, то прибавить 1, иначе вычесть 2
a = input('Введите первое число:')
b = input("Введите второе число:")

# Исключения для первого числа
while type(a) != int:
    try:
        a = int(a)
    except ValueError:
        print('Неправильно вввели!')
        a = input('Введите первое число:')
while type(b) != int:
    try:
        b = int(b)
    except ValueError:
        print('Неправильно ввели!')
        b = input('Введите второе число:')
# Находим сумму
n = a + b

# Проверяем кратность суммы 5
if n % 5 == 0:
    c = n + 1
else:
    c = n - 2

print('Результат:', c)